import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { parse, stringify } from "yaml"
import { ConfigError } from "../../../application/checking/ports.js"
import type { ConfigFile } from "../../../application/setup/ports.js"
import { type Check, type Config, REPORTS, WHENS } from "../../../domain/check.js"

export const CONFIG_FILE = "interlint.yaml"

/** The text of `interlint.yaml` for `config`, as `interlint init` writes it. */
export function renderConfig(config: Config): string {
  // lineWidth 0: a long `run` stays on one line, as the team would type it.
  return `# Generated by interlint init.\n${stringify(config, { lineWidth: 0 })}`
}

export const yamlConfigFile: ConfigFile = { path: CONFIG_FILE, render: renderConfig }

export function loadConfig(projectDir: string): Config {
  const path = join(projectDir, CONFIG_FILE)
  if (!existsSync(path)) throw new ConfigError(`${CONFIG_FILE} not found in ${projectDir}`)

  const text = readFileSync(path, "utf8")
  let raw: unknown
  try {
    raw = parse(text)
  } catch (error) {
    throw new ConfigError(`${CONFIG_FILE} is not valid YAML: ${(error as Error).message}`)
  }

  const checks = isRecord(raw) ? raw.checks : undefined
  if (!Array.isArray(checks) || checks.length === 0) {
    throw invalid("checks must be a non-empty list")
  }

  const parsed = checks.map((entry, index) => parseCheck(entry, `checks[${index}]`))
  assertUniqueNames(parsed)
  const metrics = (raw as Record<string, unknown>).metrics
  if (metrics === undefined) return { checks: parsed }
  if (typeof metrics !== "boolean") throw invalid(`metrics must be true or false (got ${JSON.stringify(metrics)})`)
  return { checks: parsed, metrics }
}

function parseCheck(entry: unknown, at: string): Check {
  if (!isRecord(entry)) throw invalid(`${at} must be a mapping with name, run, report and when`)
  const dir = optionalDir(entry, at)
  const every = optionalCount(entry, "every", at)
  const lines = optionalCount(entry, "lines", at)
  return {
    name: requireString(entry, "name", at),
    run: requireString(entry, "run", at),
    report: requireOneOf(entry, "report", REPORTS, at),
    when: requireOneOf(entry, "when", WHENS, at),
    ...(dir === undefined ? {} : { dir }),
    ...(every === undefined ? {} : { every }),
    ...(lines === undefined ? {} : { lines }),
  }
}

/**
 * How many edited files (`every`) or written lines (`lines`) the check waits for at edit: a whole number of 1 or
 * more, as a YAML number.
 */
function optionalCount(entry: Record<string, unknown>, field: "every" | "lines", at: string): number | undefined {
  const value = entry[field]
  if (value === undefined) return undefined
  if (typeof value !== "number" || !Number.isInteger(value) || value < 1) {
    throw invalid(`${at}.${field} must be a whole number of 1 or more (got ${JSON.stringify(value)})`)
  }
  return value
}

/**
 * The check's directory, `/`-separated and without `./` or a trailing `/`. `.` is the directory of
 * `interlint.yaml`, the same as no `dir`. A directory outside the project is rejected: the check would run there.
 */
function optionalDir(entry: Record<string, unknown>, at: string): string | undefined {
  if (entry.dir === undefined) return undefined
  const value = entry.dir
  const segments = typeof value === "string" ? value.split(/[\\/]/).filter((segment) => segment !== "" && segment !== ".") : []
  const absolute = typeof value === "string" && (/^[\\/]/.test(value) || /^[A-Za-z]:/.test(value))
  if (typeof value !== "string" || value.trim() === "" || absolute || segments.includes("..")) {
    throw invalid(`${at}.dir must be a directory inside the project, relative to ${CONFIG_FILE} (got "${String(value)}")`)
  }
  return segments.length === 0 ? undefined : segments.join("/")
}

function requireString(entry: Record<string, unknown>, field: string, at: string): string {
  const value = entry[field]
  if (typeof value !== "string" || value.trim() === "") {
    throw invalid(`${at}.${field} must be a non-empty string`)
  }
  return value
}

function requireOneOf<T extends string>(
  entry: Record<string, unknown>,
  field: string,
  allowed: readonly T[],
  at: string,
): T {
  const value = requireString(entry, field, at)
  if (!(allowed as readonly string[]).includes(value)) {
    throw invalid(`${at}.${field} must be one of: ${allowed.join(", ")} (got "${value}")`)
  }
  return value as T
}

function assertUniqueNames(checks: Check[]) {
  const seen = new Map<string, number>()
  checks.forEach((check, index) => {
    const first = seen.get(check.name)
    if (first !== undefined) {
      throw invalid(`checks[${index}].name "${check.name}" is already used by checks[${first}]`)
    }
    seen.set(check.name, index)
  })
}

function invalid(detail: string) {
  return new ConfigError(`${CONFIG_FILE}: ${detail}`)
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}
